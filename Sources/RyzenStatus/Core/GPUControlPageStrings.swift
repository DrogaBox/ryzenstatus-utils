/// Settings > GPU control and its menu bar panel row: the power limit held
/// through GPUSensors.kext. The page's title is `GPUControlStrings.title`.
/// The kext answers with numbers; the page shows one translated sentence per
/// group of them (`GPUControlTextGroup`) and the kext's English text under it.
struct GPUControlPageStrings {
    let stateSection: String
    let powerSection: String
    let detailsSection: String
    // States (plan 7.4).
    let ready: String
    let closed: String
    let writingOff: String
    let waitingForDriver: String
    let reverting: String
    let sleeping: String
    let heldByOther: String
    let applying: String
    /// %d = watts.
    let heldPowerFormat: String
    /// %d = watts.
    let reaskingFormat: String
    /// %d = the kext's channel version, then the app's.
    let otherVersionFormat: String
    let connectionLost: String
    let readyWarning: String
    let restartMac: String
    let lost: String
    let backAfterWake: String
    let od8NotRead: String
    // Live row.
    let liveLabel: String
    /// %1$@ board power, %2$@ fan, %3$@ hotspot, each already with its unit.
    let liveFormat: String
    // Power limit.
    let powerLabel: String
    /// %d = the start-up watts.
    let bootFormat: String
    /// %d = watts.
    let wattsFormat: String
    let backToBoot: String
    let exclusiveNote: String
    let powerFooter: String
    // Opening writing.
    let armClosed: String
    let openWriting: String
    let armPrompt: String
    let runInTerminal: String
    let copy: String
    let copied: String
    let notInstalled: String
    /// %@ = why the button is not offered, one of the `unsafe…` sentences.
    let unsafeToolFormat: String
    let armFailed: String
    // Closing changes again (kext 0.8.0, no password).
    let closeChanges: String
    /// The close button's help: what it does.
    let closeChangesHelp: String
    let closedAgain: String
    /// `stillApplied`: something is applied that the app cannot give back.
    let closeRefused: String
    /// A 0.7.x kext, which cannot close writing.
    let closeNotSupported: String
    /// A notice: writing was closed by another program (security review S-9).
    let closedByOther: String
    // The read-only card (kext 0.8.0, `WriteOff` 15).
    let readOnlyTitle: String
    let readOnlyDetail: String
    // The card's own power range (kext 0.8.0, `PowerRange`).
    /// %d = the card's floor, %d = its start-up limit, in watts.
    let cardRangeFormat: String
    /// The floor is not known: only the start-up value; also `noFloor`.
    let floorUnknown: String
    /// The floor is the start-up value: nothing to lower.
    let nothingToLower: String
    /// A notice: another program changed the GPU while the app held nothing
    /// (security review S-5).
    let otherProgramChanged: String
    // Remembering.
    let rememberToggle: String
    let rememberFooter: String
    // Details.
    let changes: String
    let reverts: String
    let kextVersion: String
    let channel: String
    // Panel row.
    let panelLabel: String
    // Groups of the kext's codes (plan 13).
    let notAllowed: String
    let busy: String
    let notReady: String
    let off: String
    let closedGroup: String
    let needsAdministrator: String
    let otherVersion: String
    let unconfirmed: String
    let notOwner: String
    let settingMissing: String
    let offNotAsExpected: String
    let offChangeUnconfirmed: String
    let offDriverStopped: String
    let offWatchdog: String
    /// %@ = the group's sentence.
    let gaveUpFormat: String
    let timedOut: String
    let notConfirmed: String
    /// The way back was asked and taken: released, not held any more.
    let backToStartUp: String
    /// The way back was asked with nothing held: nothing to give back.
    let alreadyAtStartUp: String
    // Why the arm button is not offered (plan 4), one per reason.
    let unsafeNotPlain: String
    let unsafeNotRoot: String
    let unsafeWritable: String
    let unsafeSetID: String
    let unsafeACL: String
    let unsafeUnreadable: String
    let unsafeSignature: String
    let unsafeOtherProgram: String
    // OD8 holds, for phase 3 and 4.
    /// %@ = the held settings, joined.
    let heldOD8Format: String
    let fanCurveItem: String
    let zeroRpmItem: String
    /// %d = MHz.
    let gfxItemFormat: String
    /// Between the held settings, and before the last one: "a, b and c".
    let listSeparator: String
    let listLastSeparator: String
    /// An OD8 hold in the panel row, where the whole list does not fit.
    let heldOD8Short: String
    // Accessibility (a11y A6, A13, A15).
    /// VoiceOver's hint on the power limit pop-up.
    let powerHint: String
    /// VoiceOver's hint on "Allow GPU Changes…".
    let openWritingHint: String
    /// %@ = the kext's own text, always English: said as the kext's, not as
    /// a broken translation.
    let kextSaysFormat: String
    /// A reading of the live row that is missing, in words.
    let noReading: String

    /// Why the arm button is not offered.
    func sentence(_ reason: GPUControlArmTool.UnsafeReason) -> String {
        switch reason {
        case .notPlain: return unsafeNotPlain
        case .notRoot: return unsafeNotRoot
        case .writable: return unsafeWritable
        case .setID: return unsafeSetID
        case .accessControlList: return unsafeACL
        case .unreadable: return unsafeUnreadable
        case .signature: return unsafeSignature
        case .otherProgram: return unsafeOtherProgram
        }
    }

    /// What an OD8 hold is, in words: "a fan curve and a GFX maximum of 2300 MHz".
    func od8Held(_ want: GPUControlOD8Want) -> String {
        var items: [String] = []
        if want.curve != nil { items.append(fanCurveItem) }
        if want.zeroRpmOff { items.append(zeroRpmItem) }
        if let mhz = want.gfxMaxMHz { items.append(String(format: gfxItemFormat, mhz)) }
        // An empty hold would leave "RyzenStatus is holding " with nothing
        // after it: say the short form instead.
        guard !items.isEmpty else { return heldOD8Short }
        // One sentence in every language: the last item joins with the
        // language's "and".
        let text = items.count < 2 ? items.joined()
            : items.dropLast().joined(separator: listSeparator) + listLastSeparator + items[items.count - 1]
        return String(format: heldOD8Format, text)
    }

    /// The translated sentence of one group.
    func sentence(_ group: GPUControlTextGroup) -> String {
        switch group {
        case .notAllowed: return notAllowed
        case .busy: return busy
        case .notReady: return notReady
        case .writingOff: return off
        case .closed: return closedGroup
        case .needsAdministrator: return needsAdministrator
        case .otherVersion: return otherVersion
        case .unconfirmed: return unconfirmed
        case .notOwner: return notOwner
        case .settingMissing: return settingMissing
        case .offNotAsExpected: return offNotAsExpected
        case .offChangeUnconfirmed: return offChangeUnconfirmed
        case .offDriverStopped: return offDriverStopped
        case .offWatchdog: return offWatchdog
        case .stillApplied: return closeRefused
        case .noFloor: return floorUnknown
        case .readOnlyCard: return readOnlyDetail
        }
    }

    /// Every text, for the tests.
    var all: [String] {
        [stateSection, powerSection, detailsSection, ready, closed, writingOff, waitingForDriver, reverting,
         sleeping, heldByOther, applying, heldPowerFormat, reaskingFormat, otherVersionFormat, connectionLost,
         readyWarning, restartMac, lost, backAfterWake, od8NotRead, liveLabel, liveFormat, powerLabel, bootFormat,
         wattsFormat, backToBoot, exclusiveNote, powerFooter, armClosed, openWriting, armPrompt, runInTerminal,
         copy, copied, notInstalled, unsafeToolFormat, armFailed, rememberToggle, rememberFooter, changes, reverts,
         kextVersion, channel, panelLabel, notAllowed, busy, notReady, off, closedGroup, needsAdministrator,
         otherVersion, unconfirmed, notOwner, settingMissing, offNotAsExpected, offChangeUnconfirmed,
         offDriverStopped, offWatchdog, gaveUpFormat, timedOut, notConfirmed, backToStartUp, alreadyAtStartUp,
         unsafeNotPlain, unsafeNotRoot, unsafeWritable, unsafeACL, unsafeUnreadable, unsafeSignature, unsafeOtherProgram, heldOD8Format, fanCurveItem, zeroRpmItem, gfxItemFormat,
         listSeparator, listLastSeparator, unsafeSetID, heldOD8Short, closeChanges, closeChangesHelp, closedAgain,
         closeRefused, closeNotSupported, closedByOther, readOnlyTitle, readOnlyDetail, cardRangeFormat, floorUnknown,
         nothingToLower, otherProgramChanged, powerHint, openWritingHint, kextSaysFormat, noReading]
    }
}

extension FeatureStrings {
    static func gpuControlPage(_ language: AppLanguage) -> GPUControlPageStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .zhHans: return .zhHans
        case .zhTW, .zhHK: return .zhTW
        case .uk: return .uk
        }
    }
}

