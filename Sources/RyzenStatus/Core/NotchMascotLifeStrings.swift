import Foundation

/// The companion's life: its story card, its wardrobe and the notices it
/// shows of its own. Formats take one `%d` or `%@` each.
struct NotchMascotLifeStrings {
    let bondTitle: String
    let bondHint: String
    let name: String
    let namePlaceholder: String
    let levelFormat: String
    let maxLevel: String
    let progressFormat: String
    let age: String
    let dayUnitFormat: String
    let pets: String
    let moments: String
    let daysTogetherLabel: String
    let reset: String
    let resetConfirm: String
    let accessories: String
    let accessoriesHint: String
    let lockedFormat: String
    let seasonal: String
    let seasonalHint: String
    let speech: String
    let speechHint: String
    let hardware: String
    let hardwareHint: String
    let none: String
    let bow: String
    let glasses: String
    let scarf: String
    let headphones: String
    let beanie: String
    let flower: String
    let topHat: String
    let sunglasses: String
    let crown: String
    let cap: String
    let bowTie: String
    let monocle: String
    let cowboyHat: String
    let halo: String
    let horns: String
    let chefHat: String
    let eyePatch: String
    let witchHat: String
    let santaHat: String
    let partyHat: String
    let headband: String
    let levelReachedFormat: String
    let unlockedFormat: String
    let anniversary: String
    let daysTogetherFormat: String
    let dayFormat: String
    let morning: String
    let afternoon: String
    let evening: String
    let night: String
    let gamingOn: String

    func level(_ level: Int) -> String { String(format: levelFormat, level) }
    func progress(_ done: Int, of span: Int) -> String { String(format: progressFormat, done, span) }
    func days(_ count: Int) -> String { String(format: dayUnitFormat, count) }
    func locked(at level: Int) -> String { String(format: lockedFormat, level) }
    func levelReached(_ level: Int) -> String { String(format: levelReachedFormat, level) }
    func unlockedAccessory(_ name: String) -> String { String(format: unlockedFormat, name) }
    func daysTogether(_ count: Int) -> String { String(format: daysTogetherFormat, count) }
    func dayTogether(_ day: Int) -> String { String(format: dayFormat, day) }

    func greeting(_ greeting: NotchMascotGreeting) -> String {
        switch greeting {
        case .morning: return morning
        case .afternoon: return afternoon
        case .evening: return evening
        case .night: return night
        }
    }

    func name(of accessory: NotchMascotAccessory) -> String {
        switch accessory {
        case .none: return none
        case .bow: return bow
        case .glasses: return glasses
        case .scarf: return scarf
        case .headphones: return headphones
        case .beanie: return beanie
        case .flower: return flower
        case .topHat: return topHat
        case .sunglasses: return sunglasses
        case .crown: return crown
        case .cap: return cap
        case .bowTie: return bowTie
        case .monocle: return monocle
        case .cowboyHat: return cowboyHat
        case .halo: return halo
        case .horns: return horns
        case .chefHat: return chefHat
        case .eyePatch: return eyePatch
        case .witchHat: return witchHat
        case .santaHat: return santaHat
        case .partyHat: return partyHat
        case .headband: return headband
        default:
            // The Wonder Boy wardrobe is worded in NotchMascotStrings.
            let language = L10n.shared.language
            return FeatureStrings.notchMascotRPG(language).name(of: accessory)
                ?? FeatureStrings.notchMascotShop(language).name(of: accessory) ?? ""
        }
    }
}

