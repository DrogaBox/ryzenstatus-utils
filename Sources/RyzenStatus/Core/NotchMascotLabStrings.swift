/// The lab and the mayhem: the names of their forty-eight things and a line
/// on what each does, alone or in a chain, in the order of
/// `NotchMascotAccessory.labItems` followed by `mayhemItems`.
struct NotchMascotLabStrings {
    let items: [String]
    let gags: [String]

    static let itemCount = 48

    static var order: [NotchMascotAccessory] {
        NotchMascotAccessory.labItems + NotchMascotAccessory.mayhemItems
    }

    func name(of accessory: NotchMascotAccessory) -> String? {
        Self.order.firstIndex(of: accessory).flatMap { $0 < items.count ? items[$0] : nil }
    }

    func gag(of accessory: NotchMascotAccessory) -> String? {
        Self.order.firstIndex(of: accessory).flatMap { $0 < gags.count ? gags[$0] : nil }
    }

    var isComplete: Bool {
        items.count == Self.itemCount && gags.count == Self.itemCount
            && items.allSatisfy { !$0.isEmpty } && gags.allSatisfy { !$0.isEmpty }
    }
}

