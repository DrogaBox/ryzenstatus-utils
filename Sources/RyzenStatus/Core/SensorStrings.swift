    /// "1 sensor" / "5 sensors". Russian, Ukrainian and Slovak use a
    /// "Sensors: 5" form for every count above one, so no plural rule is needed.
    func sensorCount(_ count: Int) -> String {
        count == 1 ? oneSensor : String(format: sensorsCountFormat, count)
    }

    /// The raw page's category tag; SMCDumpService keeps the English key.
    func category(_ raw: String) -> String {
        switch raw {
        case "Temperature": return categoryTemperature
        case "Fan": return categoryFan
        case "Voltage": return categoryVoltage
        case "Power": return categoryPower
        case "Current": return categoryCurrent
        default: return categoryOther
        }
    }
}

extension FeatureStrings {
    static func sensors(_ language: AppLanguage) -> SensorStrings {
        switch language {
        case .enUS: return .enUS
        case .ptBR: return .ptBR
        case .tr: return .tr
        case .ru: return .ru
        case .es: return .es
        case .sk: return .sk
        case .de: return .de
        case .fr: return .fr
        case .it: return .it
        case .ja: return .ja
        case .ko: return .ko
        case .zhHans: return .zhHans
        case .zhTW: return .zhTW
        case .zhHK: return .zhHK
        case .uk: return .uk
        }
    }
}

