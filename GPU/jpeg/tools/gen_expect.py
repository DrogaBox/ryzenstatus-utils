#!/usr/bin/env python3
"""gen_expect.py <KDK AMDRadeonX6000HWLibs> <out hwlibs_expect.hpp> <KDK AMDRadeonX6000>

Writes the table the kext checks at load: for every function it needs, the
symbol, its offset from the image header and its first 16 bytes, all read from
the KDK binary of the studied build. Run by hand when a build is added; its
output is committed as jpeg/kext/hwlibs_expect.hpp. GPU/tests/run.sh compares
the first bytes with this Mac's kernel collection when it runs that build."""
import struct, subprocess, sys, uuid

BUILD = "26.7.3 (25G342)"
# (enum name, symbol)
FUNCS = [
    ("kStartMM", "__ZN14AmdTtlServices19startMMEngineQueuesEv"),
    ("kCreateEngine", "__ZN14AmdTtlServices12createEngineE19AMD_SWIP_QUEUE_TYPEjP21_TtlCreateEngineInput"),
    ("kNotifyEngine", "__ZN14AmdTtlServices12notifyEngineE19AMD_SWIP_QUEUE_TYPEj20AMD_TTL_ENGINE_EVENT"),
    ("kQueryState", "__ZN14AmdTtlServices21queryEngineQueueStateE19AMD_SWIP_QUEUE_TYPEjP21AMD_SWIP_ENGINE_STATE"),
    ("kStopMM", "__ZN14AmdTtlServices18stopMMEngineQueuesEv"),
    ("kStopEngineQueue", "__ZN14AmdTtlServices15stopEngineQueueE19AMD_SWIP_QUEUE_TYPEj"),
    ("kTtlGetIpi", "_ttlGetIpi"),
    ("kIpiGetJpegContext", "_IpiGetJpegContext"),
    ("kJpegReadRegister", "_jpeg_internal_cgs_read_register"),
    ("kJpegCreateQueue", "_jpeg_create_queue"),
    ("kJpegStartQueue", "_jpeg_start_queue"),
    ("kJpegStopQueue", "_jpeg_stop_queue"),
    ("kJpegQueryQueueStatus", "_jpeg_query_queue_status"),
]
# The decode job (kext/kern_start.cpp: decodeRun, poolTake).
DECODE_FUNCS = [
    ("kSubmitFrame", "__ZN14AmdTtlServices11submitFrameE19AMD_SWIP_QUEUE_TYPEjPv"),
    ("kJpegAllocMemory", "_jpeg_internal_cgs_alloc_memory"),
    ("kJpegReleaseMemory", "_jpeg_internal_cgs_release_memory"),
    ("kQueueSubmitFrame", "_queue_jpeg_decode_2_0_submit_frame"),
    ("kJpegSubmitFrame", "_jpeg_submit_frame"),
]
# The power request (kext/kern_start.cpp: powerAsk); these are in AMDRadeonX6000, not in HWLibs.
POWER_FUNCS = [
    ("kSendPMCommand", "__ZN37AMDRadeonX6000_AMDGraphicsAccelerator13sendPMCommandEPv"),
]
# The door for apps (kext/kern_start.cpp: wrapVideoPM); also in AMDRadeonX6000.
APPS_FUNCS = [
    ("kVideoSendPM", "__ZN35AMDRadeonX6000_AMDAccelVideoContext13sendPMCommandEPvS0_yPy"),
]
HEAD = 16


def macho_info(path):
    """(uuid bytes, __TEXT vmaddr, [(vmaddr, vmsize, fileoff)]) of a thin x86_64 Mach-O."""
    d = open(path, "rb").read()
    magic, _, _, _, ncmds, _, _, _ = struct.unpack_from("<IiiIIIII", d, 0)
    assert magic == 0xFEEDFACF, "not a 64-bit Mach-O"
    p, uid, segs, text = 32, None, [], None
    for _ in range(ncmds):
        cmd, size = struct.unpack_from("<II", d, p)
        if cmd == 0x1B:
            uid = d[p + 8:p + 24]
        elif cmd == 0x19:
            name = d[p + 8:p + 24].split(b"\0")[0].decode()
            vmaddr, vmsize, fileoff, _ = struct.unpack_from("<QQQQ", d, p + 24)
            segs.append((vmaddr, vmsize, fileoff))
            if name == "__TEXT":
                text = vmaddr
        p += size
    return d, uid, text, segs


def symbols(path):
    out = {}
    for line in subprocess.run(["nm", path], capture_output=True, text=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "tTsSdD":
            out[parts[2]] = int(parts[0], 16)
    return out


def read_at(d, segs, addr, n):
    for vmaddr, vmsize, fileoff in segs:
        if vmaddr <= addr < vmaddr + vmsize:
            return d[fileoff + addr - vmaddr:fileoff + addr - vmaddr + n]
    raise SystemExit("address 0x%x is in no segment" % addr)


def table(path, funcs=None):
    d, uid, text, segs = macho_info(path)
    syms = symbols(path)
    rows = []
    for enum, sym in (FUNCS if funcs is None else funcs):
        if sym not in syms:
            raise SystemExit("symbol missing in %s: %s" % (path, sym))
        rows.append((enum, sym, syms[sym] - text, read_at(d, segs, syms[sym], HEAD)))
    return uid, rows


if __name__ == "__main__":
    uid, rows = table(sys.argv[1])
    o = []
    o.append("// Generated by tools/gen_expect.py from the KDK AMDRadeonX6000HWLibs of %s. Do not edit." % BUILD)
    o.append("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\nnamespace hwx {\n")
    o.append('constexpr const char* kBuild = "%s";' % BUILD)
    o.append("// LC_UUID %s" % str(uuid.UUID(bytes=uid)).upper())
    o.append("constexpr uint8_t kUuid[16]{%s};\n" % ", ".join("0x%02x" % b for b in uid))
    o.append("enum Index : size_t {")
    for enum, _, _, _ in rows:
        o.append("  %s," % enum)
    o.append("  kCount\n};\n")
    o.append("struct Function {\n  const char* symbol;\n  size_t offset;     // from the image header\n"
             "  uint8_t head[%d];  // the function's first bytes\n};" % HEAD)
    o.append("constexpr Function kFunctions[kCount]{")
    for enum, sym, off, head in rows:
        o.append('    {"%s",\n     0x%x,\n     {%s}},' % (sym, off, ", ".join("0x%02x" % b for b in head)))
    o.append("};\n")
    _, drows = table(sys.argv[1], DECODE_FUNCS)
    o.append("// the decode job")
    o.append("enum DecodeIndex : size_t {")
    for enum, _, _, _ in drows:
        o.append("  %s," % enum)
    o.append("  kDecodeCount\n};\n")
    o.append("constexpr Function kDecodeFunctions[kDecodeCount]{")
    for enum, sym, off, head in drows:
        o.append('    {"%s",\n     0x%x,\n     {%s}},' % (sym, off, ", ".join("0x%02x" % b for b in head)))
    o.append("};\n")
    xuid, xrows = table(sys.argv[3], POWER_FUNCS)
    o.append("// the power request: AMDRadeonX6000 of the same macOS build")
    o.append("// LC_UUID %s" % str(uuid.UUID(bytes=xuid)).upper())
    o.append("constexpr uint8_t kX6000Uuid[16]{%s};\n" % ", ".join("0x%02x" % b for b in xuid))
    o.append("enum PowerIndex : size_t {")
    for enum, _, _, _ in xrows:
        o.append("  %s," % enum)
    o.append("  kPowerCount\n};\n")
    o.append("constexpr Function kPowerFunctions[kPowerCount]{")
    for enum, sym, off, head in xrows:
        o.append('    {"%s",\n     0x%x,\n     {%s}},' % (sym, off, ", ".join("0x%02x" % b for b in head)))
    o.append("};\n")
    _, arows = table(sys.argv[3], APPS_FUNCS)
    o.append("// the door for apps: also in AMDRadeonX6000")
    o.append("enum AppsIndex : size_t {")
    for enum, _, _, _ in arows:
        o.append("  %s," % enum)
    o.append("  kAppsCount\n};\n")
    o.append("constexpr Function kAppsFunctions[kAppsCount]{")
    for enum, sym, off, head in arows:
        o.append('    {"%s",\n     0x%x,\n     {%s}},' % (sym, off, ", ".join("0x%02x" % b for b in head)))
    o.append("};\n\n}  // namespace hwx")
    open(sys.argv[2], "w").write("\n".join(o) + "\n")
    print("wrote %s: %d + %d functions, UUID %s" % (sys.argv[2], len(rows), len(drows), str(uuid.UUID(bytes=uid)).upper()))
